"""Code synthesis: feature file rendering + minimal step generation."""

from __future__ import annotations

import json
import re
from typing import Literal

from pydantic import BaseModel

from amtaf.llm.client import LLMClient
from amtaf.orchestrator.models import Step, TaskGraph
from amtaf.scanner.ast_index import MethodInfo

IMPORTS = {
    "HardwareDriver": "from amtaf.drivers.hardware import HardwareDriver",
    "ConsolePage": "from amtaf.drivers.gui import ConsolePage",
    "DeviceApi": "from amtaf.drivers.api import DeviceApi",
}

PROMPT = """Write ONE pytest-bdd step definition for this Gherkin step:
{text}

Reuse these existing driver methods; never re-implement them:
{methods}

Fixtures available: device (HardwareDriver), console (ConsolePage),
api (DeviceApi). Use {{name}} / {{name:d}} placeholders in the pattern for
literal values. The body must be plain Python statements, fully typed.
"""


class GeneratedStep(BaseModel):
    keyword: Literal["given", "when", "then"]
    pattern: str
    function_name: str
    params: list[str]
    docstring: str
    body: list[str]


def slugify(text: str, limit: int = 32) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:limit].strip("_")


def _literal(text: str, width: int = 48) -> str:
    """Quote ``text``, splitting long strings so black/flake8 stay happy."""
    chunks: list[str] = []
    current = ""
    for word in text.split(" "):
        if current and len(current) + len(word) + 1 > width:
            chunks.append(current + " ")
            current = word
        else:
            current = f"{current} {word}" if current else word
    chunks.append(current)
    return " ".join(json.dumps(chunk) for chunk in chunks)


def synthesize(
    step: Step, methods: list[MethodInfo], client: LLMClient
) -> GeneratedStep:
    listing = "\n".join(f"- {m.qualified}{m.signature}: {m.doc}" for m in methods)
    prompt = PROMPT.format(text=step.gherkin, methods=listing)
    return client.structured(prompt, GeneratedStep, key=f"synth_{step.id}")


def render_steps_module(steps: list[GeneratedStep]) -> str:
    keywords: list[str] = sorted({s.keyword for s in steps})
    needs_time = any("time." in line for s in steps for line in s.body)
    lines = [
        '"""Generated by AMTAF. Review before merging."""',
        "from __future__ import annotations",
        "",
    ]
    if needs_time:
        lines.append("import time")
        lines.append("")
    lines.append(f"from pytest_bdd import {', '.join(['parsers'] + keywords)}")
    all_params = " ".join(p for s in steps for p in s.params)
    lines += [imp for name, imp in IMPORTS.items() if name in all_params]
    for step in steps:
        lines += ["", ""]
        lines.append(f"@{step.keyword}(parsers.parse({_literal(step.pattern)}))")
        lines.append(f"def {step.function_name}({', '.join(step.params)}) -> None:")
        lines.append(f"    {json.dumps(step.docstring)}")
        lines += [f"    {line}" for line in step.body]
    return "\n".join(lines) + "\n"


def render_feature(
    graph: TaskGraph,
    *,
    feature: str,
    priority: str,
    ticket: str,
    environment: str,
) -> str:
    layer_tags = " ".join(
        f"@layer={layer.value.split('_')[0].lower()}" for layer in graph.layers()
    )
    out = [
        f"@feature={feature} {layer_tags} @priority={priority} @ticket={ticket}",
        f"Feature: {graph.intent}",
        "",
        f"  @smoke @environment={environment}",
        f"  Scenario: {graph.intent}",
    ]
    previous = ""
    for step in graph.steps:
        word = "And" if step.keyword == previous else step.keyword
        out.append(f"    {word} {step.gherkin}")
        previous = step.keyword
    return "\n".join(out) + "\n"
