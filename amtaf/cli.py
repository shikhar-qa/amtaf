"""CLI: ``amtaf generate "<plain-English intent>"``."""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

from amtaf.llm.client import LLMClient, RecordedClient, get_client
from amtaf.orchestrator.models import Step, TaskGraph
from amtaf.orchestrator.planner import plan
from amtaf.scanner.ast_index import index_methods, index_steps
from amtaf.scanner.matching import Decision, Match, StepIndex
from amtaf.synth.generator import (
    GeneratedStep,
    render_feature,
    render_steps_module,
    slugify,
    synthesize,
)
from amtaf.synth.lint_gate import LintResult, run_gate


class NeedsHuman(Exception):
    """Raised when inferred SLAs or gray-zone matches need confirmation."""


@dataclass
class GenerationResult:
    graph: TaskGraph
    matches: dict[str, Match]
    generated: list[GeneratedStep]
    files: list[Path]
    lint: LintResult | None


def generate(
    intent: str,
    root: Path,
    *,
    client: LLMClient | None = None,
    out_dir: Path | None = None,
    assume_yes: bool = False,
    priority: str = "p1",
    ticket: str = "DEMO-1",
    environment: str = "docker_demo",
    lint: bool = True,
) -> GenerationResult:
    client = client or get_client()
    out_dir = out_dir or root / "generated"
    graph = plan(intent, client)

    pending: list[Step] = graph.pending_confirmations()
    if pending and not assume_yes:
        names = ", ".join(f"{s.id} ({s.sla_seconds}s)" for s in pending)
        raise NeedsHuman(
            f"Inferred SLAs need confirmation: {names}. Re-run with --yes."
        )

    step_index = StepIndex(index_steps(root / "tests" / "existing"))
    methods = index_methods(root / "amtaf" / "drivers")
    matches = {s.id: step_index.match(s.gherkin) for s in graph.steps}

    review = [m for m in matches.values() if m.decision is Decision.REVIEW]
    if review and not assume_yes:
        texts = "; ".join(
            f"'{m.text}' ~ {m.step.pattern if m.step else '?'}" for m in review
        )
        raise NeedsHuman(f"Gray-zone matches need review: {texts}. Re-run with --yes.")

    generated = [
        synthesize(step, methods, client)
        for step in graph.steps
        if matches[step.id].decision is not Decision.REUSE
    ]

    slug = slugify(intent)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "__init__.py").touch()
    feature_path = out_dir / f"{slug}.feature"
    feature_path.write_text(
        render_feature(
            graph,
            feature=slug[:24],
            priority=priority,
            ticket=ticket,
            environment=environment,
        )
    )
    files = [feature_path]
    py_files: list[Path] = []
    test_lines = [
        '"""Generated by AMTAF. Review before merging."""',
        "from pytest_bdd import scenarios",
    ]
    if generated:
        steps_path = out_dir / f"steps_{slug}.py"
        steps_path.write_text(render_steps_module(generated))
        py_files.append(steps_path)
        test_lines.append(
            f"from {out_dir.name}.steps_{slug} import *  # noqa: F401,F403"
        )
    test_lines += ["", f'scenarios("{feature_path.name}")', ""]
    test_path = out_dir / f"test_{slug}.py"
    test_path.write_text("\n".join(test_lines))
    py_files.append(test_path)
    files += py_files

    lint_result = run_gate(py_files, root) if lint else None
    return GenerationResult(graph, matches, generated, files, lint_result)


def print_report(result: GenerationResult, root: Path | None = None) -> None:
    root = root or Path.cwd()
    print("\nTask graph")
    for s in result.graph.steps:
        sla = f" sla={s.sla_seconds}s ({s.sla_source})" if s.sla_seconds else ""
        print(f"  {s.id}  {s.layer.value:<13} {s.keyword:<5} {s.gherkin}{sla}")
    print("\nReuse report")
    for sid, m in result.matches.items():
        target = (
            f"{Path(m.step.file).relative_to(root)}::{m.step.function}"
            if m.step
            else "-"
        )
        print(f"  {sid}  {m.decision.value:<8} {m.score:.2f}  {target}")
    reused = sum(m.decision is Decision.REUSE for m in result.matches.values())
    print(f"\nReused {reused}, generated {len(result.generated)}")
    print("Files: " + ", ".join(str(p.relative_to(root)) for p in result.files))
    if result.lint:
        print(f"Static checks: {'PASS' if result.lint.ok else 'FAIL'}")
        if not result.lint.ok:
            print(result.lint.details)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="amtaf")
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate", help="plain English -> feature + steps")
    gen.add_argument("intent")
    gen.add_argument(
        "--yes", action="store_true", help="accept inferred SLAs/gray-zone"
    )
    gen.add_argument("--ticket", default="DEMO-1")
    gen.add_argument("--priority", default="p1", choices=["p0", "p1", "p2"])
    args = parser.parse_args(argv)

    client = get_client()
    if isinstance(client, RecordedClient):
        print("[recorded mode: replaying canned demo responses, not calling an LLM]")
    try:
        result = generate(
            args.intent,
            Path.cwd(),
            client=client,
            assume_yes=args.yes,
            ticket=args.ticket,
            priority=args.priority,
        )
    except NeedsHuman as exc:
        print(f"Needs human review: {exc}")
        return 2
    print_report(result)
    return 0 if result.lint is None or result.lint.ok else 1


if __name__ == "__main__":
    sys.exit(main())
